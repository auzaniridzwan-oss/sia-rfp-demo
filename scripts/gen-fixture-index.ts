/**
 * Writes packages/data/src/fixtures.ts: a static import of every SerpAPI fixture so the
 * server bundle (esbuild) includes them. Run after `pnpm spike:serpapi` adds fixtures.
 */
import { readdirSync, writeFileSync } from 'node:fs';

const dir = 'packages/data/fixtures/serpapi';
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const lines = files.map((f, i) => `import f${i} from '../fixtures/serpapi/${f}';`);
const entries = files.map((f, i) => {
  const [airline, route, date] = f.replace('.json', '').split('_');
  const [from, to] = route!.split('-');
  return `  { airline: '${airline}', from: '${from}', to: '${to}', date: '${date}', data: f${i} as SerpApiFixture },`;
});
writeFileSync(
  'packages/data/src/fixtures.ts',
  `// Generated by scripts/gen-fixture-index.ts — do not edit.\n${lines.join('\n')}\n\n` +
    `/** Slimmed SerpAPI google_flights response (best_flights + other_flights only). */\n` +
    `export interface SerpApiFixture { best_flights?: unknown[]; other_flights?: unknown[] }\n\n` +
    `export interface FixtureEntry { airline: string; from: string; to: string; date: string; data: SerpApiFixture }\n\n` +
    `export const SERPAPI_FIXTURES: FixtureEntry[] = [\n${entries.join('\n')}\n];\n`,
);
console.log(`Indexed ${files.length} fixtures`);
